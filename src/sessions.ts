import fs from "node:fs";
import path from "node:path";
import readline from "node:readline";

export const MAX_TAIL_TURNS = 10;

export interface Turn {
  timestamp: string | null;
  user: string;
  assistant: string;
}

export interface ParsedSession {
  sessionId: string | null;
  startedAt: string | null;
  lastActivityAt: string | null;
  firstPrompt: string | null;
  lastAssistantReply: string | null;
  messageCount: number;
  /** The last MAX_TAIL_TURNS turns. */
  turns: Turn[];
}

/** Claude Code stores sessions under ~/.claude/projects/<cwd with every non-alphanumeric char replaced by "-">. */
export function encodeProjectPath(absPath: string): string {
  return absPath.replace(/[^a-zA-Z0-9]/g, "-");
}

export function isValidSessionId(id: string): boolean {
  return /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/.test(id);
}

function textOf(content: unknown): string {
  if (typeof content === "string") return content;
  if (!Array.isArray(content)) return "";
  const parts: string[] = [];
  for (const block of content) {
    if (block && typeof block === "object" && (block as { type?: unknown }).type === "text") {
      const t = (block as { text?: unknown }).text;
      if (typeof t === "string") parts.push(t);
    }
  }
  return parts.join("\n");
}

/** Harness-injected user entries (command wrappers, reminders, interrupts) are not real prompts. */
function isSyntheticUserText(text: string): boolean {
  const t = text.trimStart();
  return (
    t === "" ||
    t.startsWith("<command-name>") ||
    t.startsWith("<command-message>") ||
    t.startsWith("<local-command-") ||
    t.startsWith("<system-reminder>") ||
    t.startsWith("<task-notification>") ||
    t.startsWith("Caveat: The messages below were generated by the user while running local commands") ||
    t.startsWith("[Request interrupted")
  );
}

/** Incremental parser for one session transcript (JSONL). Malformed lines are skipped. */
export class SessionParser {
  private s: ParsedSession = {
    sessionId: null,
    startedAt: null,
    lastActivityAt: null,
    firstPrompt: null,
    lastAssistantReply: null,
    messageCount: 0,
    turns: [],
  };

  push(line: string): void {
    // Cheap prefilter: transcripts also hold large bookkeeping entries we never need.
    if (!line.includes('"type":"user"') && !line.includes('"type":"assistant"') && !line.includes('"type": "')) return;
    let o: Record<string, unknown>;
    try {
      o = JSON.parse(line) as Record<string, unknown>;
    } catch {
      return;
    }
    if (!o || typeof o !== "object") return;
    if (o.type !== "user" && o.type !== "assistant") return;
    if (o.isSidechain === true || o.isMeta === true) return;
    const message = o.message as { content?: unknown } | undefined;
    if (!message || typeof message !== "object") return;
    const text = textOf(message.content).trim();
    const ts = typeof o.timestamp === "string" ? o.timestamp : null;
    const s = this.s;
    if (!s.sessionId && typeof o.sessionId === "string") s.sessionId = o.sessionId;
    if (ts) {
      if (!s.startedAt) s.startedAt = ts;
      s.lastActivityAt = ts;
    }

    if (o.type === "user") {
      if (isSyntheticUserText(text)) return; // tool results and harness-injected entries
      s.messageCount++;
      if (s.firstPrompt === null) s.firstPrompt = text;
      s.turns.push({ timestamp: ts, user: text, assistant: "" });
      if (s.turns.length > MAX_TAIL_TURNS) s.turns.shift();
    } else {
      if (!text) return; // thinking / tool_use only
      s.messageCount++;
      s.lastAssistantReply = text;
      let turn = s.turns[s.turns.length - 1];
      if (!turn) {
        turn = { timestamp: ts, user: "", assistant: "" };
        s.turns.push(turn);
      }
      turn.assistant = turn.assistant ? `${turn.assistant}\n\n${text}` : text;
    }
  }

  result(): ParsedSession {
    return this.s;
  }
}

export function parseSessionLines(lines: Iterable<string>): ParsedSession {
  const p = new SessionParser();
  for (const line of lines) p.push(line);
  return p.result();
}

export async function parseSessionFile(file: string): Promise<ParsedSession> {
  const p = new SessionParser();
  const rl = readline.createInterface({ input: fs.createReadStream(file, { encoding: "utf8" }), crlfDelay: Infinity });
  for await (const line of rl) p.push(line);
  const s = p.result();
  if (!s.sessionId) s.sessionId = path.basename(file, ".jsonl");
  return s;
}

export function sessionsDir(claudeHomeDir: string, projectPath: string): string {
  return path.join(claudeHomeDir, "projects", encodeProjectPath(projectPath));
}

/** Session files in a project, most recently modified first. */
export function listSessionFiles(dir: string): { file: string; mtimeMs: number }[] {
  let names: string[];
  try {
    names = fs.readdirSync(dir);
  } catch {
    return [];
  }
  const out: { file: string; mtimeMs: number }[] = [];
  for (const n of names) {
    if (!n.endsWith(".jsonl")) continue;
    const file = path.join(dir, n);
    try {
      const st = fs.statSync(file);
      if (st.isFile()) out.push({ file, mtimeMs: st.mtimeMs });
    } catch {
      /* ignore */
    }
  }
  return out.sort((a, b) => b.mtimeMs - a.mtimeMs);
}
